import random

# Ant Colony Optimization for Dynamic Telecommunication Routing

class TelecommunicationNetwork:
    def __init__(self):
        # Network links: (Router 1, Router 2): (delay, congestion)
        self.graph = {
            ('A', 'B'): [2, 1],
            ('A', 'C'): [4, 2],
            ('B', 'C'): [1, 1],
            ('B', 'D'): [5, 2],
            ('C', 'D'): [2, 1],
            ('C', 'E'): [4, 2],
            ('D', 'E'): [1, 1]
        }

        self.pheromone = {edge: 1.0 for edge in self.graph}
        self.alpha = 1.0
        self.beta = 2.0
        self.evaporation = 0.3

    def get_neighbors(self, node):
        neighbors = []
        for (u, v), values in self.graph.items():
            if u == node:
                neighbors.append((v, values))
            elif v == node:
                neighbors.append((u, values))
        return neighbors

    def edge_key(self, u, v):
        return (u, v) if (u, v) in self.graph else (v, u)

    def route_cost(self, route):
        cost = 0
        for i in range(len(route) - 1):
            edge = self.edge_key(route[i], route[i + 1])
            delay, congestion = self.graph[edge]
            cost += delay + congestion
        return cost

    def construct_route(self, source, destination):
        route = [source]
        current = source
        visited = {source}

        while current != destination:
            choices = []

            for neighbor, values in self.get_neighbors(current):
                if neighbor not in visited:
                    edge = self.edge_key(current, neighbor)
                    delay, congestion = values

                    # Lower delay and congestion are preferred
                    heuristic = 1.0 / (delay + congestion)
                    weight = (
                        self.pheromone[edge] ** self.alpha
                        * heuristic ** self.beta
                    )
                    choices.append((neighbor, weight))

            if not choices:
                return None

            total = sum(weight for _, weight in choices)
            if total <= 0:
                return None

            probabilities = [weight / total for _, weight in choices]
            next_node = random.choices(
                [node for node, _ in choices],
                weights=probabilities,
                k=1
            )[0]

            route.append(next_node)
            visited.add(next_node)
            current = next_node

        return route

    def update_pheromones(self, routes):
        # Evaporate old pheromone trails
        for edge in self.pheromone:
            self.pheromone[edge] *= (1 - self.evaporation)

        # Better routes receive more pheromone
        for route in routes:
            cost = self.route_cost(route)
            deposit = 10.0 / cost

            for i in range(len(route) - 1):
                edge = self.edge_key(route[i], route[i + 1])
                self.pheromone[edge] += deposit

    def change_network(self):
        # Simulate changing congestion and delay
        edge = random.choice(list(self.graph.keys()))
        self.graph[edge][1] = random.randint(1, 6)
        self.graph[edge][0] = random.randint(1, 5)

        print("\nNetwork conditions changed on link", edge)

    def run_aco(self, source, destination, ants=10, iterations=20):
        best_route = None
        best_cost = float("inf")

        for iteration in range(iterations):
            routes = []

            for _ in range(ants):
                route = self.construct_route(source, destination)

                if route:
                    routes.append(route)
                    cost = self.route_cost(route)

                    if cost < best_cost:
                        best_cost = cost
                        best_route = route[:]

            self.update_pheromones(routes)

            # Simulate dynamic network changes
            if iteration > 0 and iteration % 5 == 0:
                self.change_network()

            print(
                f"Iteration {iteration + 1}: "
                f"Best cost = {best_cost}"
            )

        return best_route, best_cost


# Main program
if __name__ == "__main__":
    random.seed(42)

    network = TelecommunicationNetwork()

    source = 'A'
    destination = 'E'

    print("ANT COLONY OPTIMIZATION")
    print("Dynamic Telecommunication Network Routing")
    print("Source Router:", source)
    print("Destination Router:", destination)

    best_route, best_cost = network.run_aco(
        source, destination,
        ants=10,
        iterations=20
    )

    print("\n----- FINAL RESULT -----")

    if best_route:
        print("Optimal Route:", " -> ".join(best_route))
        print("Total Route Cost:", best_cost)
    else:
        print("No route found!")