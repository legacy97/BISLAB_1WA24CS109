import random
import math

# =============================================================================
# 1. DEFINE THE PROBLEM
# =============================================================================
# Environment setup: 10x10 grid map
START = (0, 0)
GOAL = (10, 10)
OBSTACLES = [(3, 3), (3, 4), (3, 5), (6, 5), (6, 6), (6, 7)] # Static obstacle coordinates
NUM_WAYPOINTS = 5 # Number of inner path steps between Start and Goal

def distance(p1, p2):
    """Calculates Euclidean distance between two points."""
    return math.sqrt((p1[0] - p2[0])**2 + (p1[1] - p2[1])**2)

def is_collision(p):
    """Checks if a point hits or sits too close to an obstacle."""
    # Round to check grid alignment
    rx, ry = round(p[0]), round(p[1])
    return (rx, ry) in OBSTACLES

# =============================================================================
# 2. INITIALIZE PARAMETERS
# =============================================================================
POP_SIZE = 100       # Size of the population
MUT_RATE = 0.1       # Probability of mutation per waypoint
CROSS_RATE = 0.8     # Probability of crossover between two parents
GENERATIONS = 200    # Number of iterations/generations
GRID_MAX = 10        # Max boundary of our map space

# =============================================================================
# 3. CREATE INITIAL POPULATION
# =============================================================================
def create_initial_population():
    """Generates an initial population of random paths."""
    population = []
    for _ in range(POP_SIZE):
        # A path consists of random points inside the grid boundaries
        path = []
        for _ in range(NUM_WAYPOINTS):
            x = random.uniform(0, GRID_MAX)
            y = random.uniform(0, GRID_MAX)
            path.append((x, y))
        population.append(path)
    return population

# =============================================================================
# 4. EVALUATE FITNESS
# =============================================================================
def evaluate_fitness(path):
    """Evaluates the fitness of a path. Higher is better."""
    # Reconstruct the full path including Start and Goal
    full_path = [START] + path + [GOAL]

    total_length = 0
    collisions = 0

    # Calculate path length and track collisions along segments
    for i in range(len(full_path) - 1):
        p1 = full_path[i]
        p2 = full_path[i+1]
        total_length += distance(p1, p2)

        # Sample points along the segment to check for intermediate collisions
        steps = 10
        for s in range(steps + 1):
            t = s / steps
            inter_x = p1[0] + t * (p2[0] - p1[0])
            inter_y = p1[1] + t * (p2[1] - p1[1])
            if is_collision((inter_x, inter_y)):
                collisions += 1

    # Fitness function: penalize distance and heavily penalize collisions
    # Adding 1e-6 prevents division by zero
    penalty = collisions * 100
    fitness_score = 1.0 / (total_length + penalty + 1e-6)
    return fitness_score

# =============================================================================
# 5. SELECTION
# =============================================================================
def tournament_selection(population, fitness_scores, k=3):
    """Selects the best individual from a random group of size k."""
    selected_indices = random.sample(range(len(population)), k)
    best_idx = max(selected_indices, key=lambda idx: fitness_scores[idx])
    return population[best_idx]

# =============================================================================
# 6. CROSSOVER
# =============================================================================
def crossover(parent1, parent2):
    """Performs single-point crossover between two parents."""
    if random.random() < CROSS_RATE:
        point = random.randint(1, NUM_WAYPOINTS - 1)
        child1 = parent1[:point] + parent2[point:]
        child2 = parent2[:point] + parent1[point:]
        return child1, child2
    return parent1.copy(), parent2.copy()

# =============================================================================
# 7. MUTATION
# =============================================================================
def mutate(path):
    """Applies random mutation to coordinates within grid bounds."""
    mutated_path = []
    for waypoint in path:
        if random.random() < MUT_RATE:
            # Shift coordinate randomly within bounds
            x = max(0, min(GRID_MAX, waypoint[0] + random.uniform(-1.5, 1.5)))
            y = max(0, min(GRID_MAX, waypoint[1] + random.uniform(-1.5, 1.5)))
            mutated_path.append((x, y))
        else:
            mutated_path.append(waypoint)
    return mutated_path

# =============================================================================
# 8. ITERATION (MAIN EXECUTION LOOP)
# =============================================================================
def main():
    # Step 3: Populate
    population = create_initial_population()

    best_overall_path = None
    best_overall_fitness = -1

    print(f"Starting Genetic Algorithm Path Finding Optimization...")
    print(f"Start Point: {START} -> Goal Point: {GOAL}\n")

    for generation in range(1, GENERATIONS + 1):
        # Step 4: Evaluate
        fitness_scores = [evaluate_fitness(ind) for ind in population]

        # Track historical best path
        max_fitness = max(fitness_scores)
        best_idx = fitness_scores.index(max_fitness)

        if max_fitness > best_overall_fitness:
            best_overall_fitness = max_fitness
            best_overall_path = population[best_idx]

        # Log progress every 20 generations
        if generation % 20 == 0 or generation == 1:
            # Calculate distance without penalty for reporting
            full_b = [START] + best_overall_path + [GOAL]
            d = sum(distance(full_b[i], full_b[i+1]) for i in range(len(full_b)-1))
            print(f"Generation {generation:3d} | Best Fitness: {max_fitness:.5f} | Current Valid Distance: {d:.2f}")

        # Create the next generation
        new_population = []
        while len(new_population) < POP_SIZE:
            # Step 5: Selection
            p1 = tournament_selection(population, fitness_scores)
            p2 = tournament_selection(population, fitness_scores)

            # Step 6: Crossover
            c1, c2 = crossover(p1, p2)

            # Step 7: Mutation
            c1 = mutate(c1)
            c2 = mutate(c2)

            new_population.extend([c1, c2])

        population = new_population[:POP_SIZE]

    # =========================================================================
    # 9. OUTPUT THE BEST SOLUTION
    # =========================================================================
    print("\n==================================================")
    print("OPTIMIZATION COMPLETE - BEST PATH FOUND")
    print("==================================================")
    final_full_path = [START] + best_overall_path + [GOAL]

    print("Sequential Waypoints:")
    for idx, pt in enumerate(final_full_path):
        print(f"  Step {idx}: ({pt[0]:.2f}, {pt[1]:.2f})")

    final_dist = sum(distance(final_full_path[i], final_full_path[i+1]) for i in range(len(final_full_path)-1))
    print(f"\nFinal Optimized Path Length: {final_dist:.2f} units")

if __name__ == "__main__":
    main()

"""### Particle Swarm Optimization (PSO) Pathfinding Implementation
In this implementation, each particle is a candidate route composed of 5 continuous coordinate waypoints. The particles travel through this 5-dimensional coordinate space, continuously pulling themselves towards their own personal best configurations and the entire swarm's overall global best configuration.

### 3D Drone Pathfinding Optimization using PSO
This model simulates a drone flying from a launchpad $(0, 0, 0)$ to a landing zone $(10, 10, 8)$. It avoids 3D cylindrical column obstacles (like buildings/trees) while minimizing total flight distance, altitude climbing work, and path sharpness.
"""

import random
import math

# =============================================================================
# 3D ENVIRONMENT DEFINITION
# =============================================================================
START_3D = (0.0, 0.0, 0.0)      # Launchpad
GOAL_3D = (10.0, 10.0, 8.0)     # Target landing zone
MAP_LIMIT = 10.0
NUM_DRONE_WAYPOINTS = 4         # Intermediate waypoints

# Cylindrical obstacles: (center_x, center_y, radius, height)
OBSTACLES_3D = [
    (3.0, 3.0, 1.5, 8.0),       # Building 1
    (6.0, 6.0, 2.0, 9.0),       # Building 2
    (3.0, 7.0, 1.2, 10.0)       # Building 3
]

# =============================================================================
# HELPER MATHEMATICS FOR 3D FLIGHT
# =============================================================================
def distance_3d(p1, p2):
    return math.sqrt((p1[0]-p2[0])**2 + (p1[1]-p2[1])**2 + (p1[2]-p2[2])**2)

def is_collision_3d(p):
    """Checks if drone point intersects with any 3D cylindrical obstacle."""
    px, py, pz = p
    for (cx, cy, r, h) in OBSTACLES_3D:
        # Check if within cylinder radius horizontally and below cylinder height
        dist_horizontal = math.sqrt((px - cx)**2 + (py - cy)**2)
        if dist_horizontal <= r and pz <= h:
            return True
    return False

def evaluate_drone_flight(path):
    """Evaluates total flight safety, energy, and path smoothness."""
    full_path = [START_3D] + path + [GOAL_3D]

    total_length = 0.0
    energy_cost = 0.0
    collisions = 0
    sharpness_penalty = 0.0

    for i in range(len(full_path) - 1):
        p1 = full_path[i]
        p2 = full_path[i+1]

        dist = distance_3d(p1, p2)
        total_length += dist

        # Ascent consumes double the energy, descent is cheap
        dz = p2[2] - p1[2]
        climb_factor = 2.0 if dz > 0 else 0.5
        energy_cost += (dist + abs(dz) * climb_factor)

        # Sample flight segment for collisions
        steps = 8
        for s in range(steps + 1):
            t = s / steps
            inter_pt = (
                p1[0] + t * (p2[0] - p1[0]),
                p1[1] + t * (p2[1] - p1[1]),
                p1[2] + t * (p2[2] - p1[2])
            )
            if is_collision_3d(inter_pt):
                collisions += 1

    # Calculate sharpness (sudden changes in flight vectors)
    for i in range(1, len(full_path) - 1):
        v1 = (full_path[i][0]-full_path[i-1][0], full_path[i][1]-full_path[i-1][1], full_path[i][2]-full_path[i-1][2])
        v2 = (full_path[i+1][0]-full_path[i][0], full_path[i+1][1]-full_path[i][1], full_path[i+1][2]-full_path[i][2])
        len1 = math.sqrt(v1[0]**2 + v1[1]**2 + v1[2]**2) + 1e-6
        len2 = math.sqrt(v2[0]**2 + v2[1]**2 + v2[2]**2) + 1e-6
        dot_prod = v1[0]*v2[0] + v1[1]*v2[1] + v1[2]*v2[2]
        cos_angle = max(-1.0, min(1.0, dot_prod / (len1 * len2)))
        angle = math.acos(cos_angle) # angle in radians
        if angle > math.pi / 4: # Penalize turns sharper than 45 degrees
            sharpness_penalty += (angle * 10.0)

    total_penalty = (collisions * 250.0) + (sharpness_penalty * 5.0)
    fitness = 1.0 / (energy_cost + total_penalty + 1e-6)
    return fitness

# =============================================================================
# Drone PSO CLASS
# =============================================================================
class DroneParticle:
    def __init__(self):
        self.position = []
        for _ in range(NUM_DRONE_WAYPOINTS):
            x = random.uniform(0, MAP_LIMIT)
            y = random.uniform(0, MAP_LIMIT)
            z = random.uniform(1.0, MAP_LIMIT)  # Drones fly above ground
            self.position.append((x, y, z))

        self.velocity = [[0.0, 0.0, 0.0] for _ in range(NUM_DRONE_WAYPOINTS)]
        self.best_position = list(self.position)
        self.best_fitness = evaluate_drone_flight(self.position)

    def update_position(self):
        new_pos = []
        for i in range(NUM_DRONE_WAYPOINTS):
            x = max(0.0, min(MAP_LIMIT, self.position[i][0] + self.velocity[i][0]))
            y = max(0.0, min(MAP_LIMIT, self.position[i][1] + self.velocity[i][1]))
            z = max(0.5, min(MAP_LIMIT, self.position[i][2] + self.velocity[i][2])) # Minimum 0.5m clearance
            new_pos.append((x, y, z))
        self.position = new_pos

# =============================================================================
# RUN OPTIMIZATION
# =============================================================================
def run_drone_pso():
    swarm = [DroneParticle() for _ in range(60)]
    g_best_pos = None
    g_best_fit = -1.0

    # Establish Global Best
    for p in swarm:
        if p.best_fitness > g_best_fit:
            g_best_fit = p.best_fitness
            g_best_pos = list(p.best_position)

    for it in range(1, 151):
        for p in swarm:
            for w in range(NUM_DRONE_WAYPOINTS):
                r1, r2 = random.random(), random.random()

                # Cognitive & Social force calculation in 3D
                cog = [1.5 * r1 * (p.best_position[w][dim] - p.position[w][dim]) for dim in range(3)]
                soc = [1.5 * r2 * (g_best_pos[w][dim] - p.position[w][dim]) for dim in range(3)]

                # Update 3D Velocity vectors
                for dim in range(3):
                    v_new = 0.6 * p.velocity[w][dim] + cog[dim] + soc[dim]
                    p.velocity[w][dim] = max(-1.5, min(1.5, v_new)) # Cap speed

            p.update_position()
            fit = evaluate_drone_flight(p.position)

            if fit > p.best_fitness:
                p.best_fitness = fit
                p.best_position = list(p.position)

            if fit > g_best_fit:
                g_best_fit = fit
                g_best_pos = list(p.position)

    # Result Summary
    print("\n--- 3D Drone Flight Path Optimization Complete ---")
    final_route = [START_3D] + g_best_pos + [GOAL_3D]
    for i, step in enumerate(final_route):
        desc = "Launchpad" if i == 0 else ("Landing Zone" if i == len(final_route)-1 else f"Waypoint {i}")
        print(f"  {desc:12s} -> (X: {step[0]:.2f}m, Y: {step[1]:.2f}m, Altitude: {step[2]:.2f}m)")

run_drone_pso()